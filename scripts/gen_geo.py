"""Writes src/universe/05-geo.js: the lower-48 US state outlines as SVG paths, plus the projection the page uses
to place stadiums on them. Standard library only. Run: python3 -I scripts/gen_geo.py [--src file.geojson]

Source: Natural Earth 1:110m cultural vectors, admin-1 states and provinces (ne_110m_admin_1_states_provinces),
https://www.naturalearthdata.com/ via the GitHub mirror below. Natural Earth is in the public domain: no permission
is needed to use it and no attribution is required (we credit it anyway).

Projection: Albers equal-area conic, standard parallels 29.5N and 45.5N, origin 37.5N 96W (the usual choice for
maps of the contiguous United States). The same constants are written into the JavaScript so stadium positions
line up with the outlines exactly. Outlines are simplified with Douglas-Peucker in projected pixels."""
import argparse, json, math, os, sys, tempfile, urllib.request

URL = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_admin_1_states_provinces.geojson"
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
W, H, PAD = 960, 600, 18
TOLERANCE = 0.35         # pixels; keeps the file small while state shapes stay recognisable
SKIP = {"AK", "HI"}      # lower 48 plus DC

PHI1, PHI2, PHI0, LAM0 = 29.5, 45.5, 37.5, -96.0
R = math.radians
N = (math.sin(R(PHI1)) + math.sin(R(PHI2))) / 2
C = math.cos(R(PHI1)) ** 2 + 2 * N * math.sin(R(PHI1))
RHO0 = math.sqrt(C - 2 * N * math.sin(R(PHI0))) / N

def albers(lat, lon):
    rho = math.sqrt(C - 2 * N * math.sin(R(lat))) / N
    th = N * R(lon - LAM0)
    return rho * math.sin(th), RHO0 - rho * math.cos(th)

def dp(pts, tol):
    """Douglas-Peucker simplification of an open polyline (list of (x, y))."""
    if len(pts) < 3: return pts
    keep = [False] * len(pts); keep[0] = keep[-1] = True; stack = [(0, len(pts) - 1)]
    while stack:
        a, b = stack.pop(); (ax, ay), (bx, by) = pts[a], pts[b]; dx, dy = bx - ax, by - ay; L = math.hypot(dx, dy)
        best, idx = -1.0, -1
        for i in range(a + 1, b):
            px, py = pts[i]
            d = math.hypot(px - ax, py - ay) if L == 0 else abs(dy * px - dx * py + bx * ay - by * ax) / L
            if d > best: best, idx = d, i
        if best > tol: keep[idx] = True; stack += [(a, idx), (idx, b)]
    return [p for p, k in zip(pts, keep) if k]

def rings(geom):
    if geom["type"] == "Polygon": return geom["coordinates"]
    if geom["type"] == "MultiPolygon": return [r for poly in geom["coordinates"] for r in poly]
    return []

def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--src", help="a saved copy of the GeoJSON (skips the download)")
    ap.add_argument("--out", default=os.path.join(ROOT, "src", "universe", "05-geo.js")); a = ap.parse_args()
    if a.src: path = a.src
    else:
        d = tempfile.mkdtemp(prefix="nfl-geo-"); path = os.path.join(d, "states.geojson")
        with urllib.request.urlopen(URL, timeout=60) as r, open(path, "wb") as f: f.write(r.read())
    data = json.load(open(path, encoding="utf-8"))
    feats = [f for f in data["features"] if f["properties"].get("iso_a2") == "US" and f["properties"].get("postal") not in SKIP]
    raw = [(f["properties"]["postal"], [[albers(lat, lon) for lon, lat in ring] for ring in rings(f["geometry"])]) for f in feats]
    xs = [x for _, rs in raw for r in rs for x, _ in r]; ys = [y for _, rs in raw for r in rs for _, y in r]
    s = min((W - 2 * PAD) / (max(xs) - min(xs)), (H - 2 * PAD) / (max(ys) - min(ys)))
    tx = (W - s * (max(xs) + min(xs))) / 2; ty = (H + s * (max(ys) + min(ys))) / 2
    out = []
    for postal, rs in sorted(raw):
        parts = []
        for r in rs:
            pts = dp([(s * x + tx, ty - s * y) for x, y in r], TOLERANCE)
            if len(pts) < 4: continue
            q = [(round(x, 1), round(y, 1)) for x, y in pts]
            seg = "M%g %g" % q[0]
            for (x0, y0), (x1, y1) in zip(q, q[1:-1] if q[-1] == q[0] else q[1:]):
                seg += "l%g %g" % (round(x1 - x0, 1), round(y1 - y0, 1))
            parts.append(seg + "z")
        if parts: out.append([postal, "".join(parts)])
    js = ("// Generated by scripts/gen_geo.py. Do not edit by hand.\n"
          "// Lower-48 US state outlines from Natural Earth 1:110m admin-1 (public domain, naturalearthdata.com),\n"
          "// Albers equal-area conic (parallels 29.5N/45.5N, origin 37.5N 96W), fitted to a %dx%d box.\n" % (W, H) +
          "var GEO={w:%d,h:%d,states:%s};\n" % (W, H, json.dumps(out, separators=(",", ":"))) +
          "var GEO_P={n:%r,c:%r,rho0:%r,s:%r,tx:%r,ty:%r,lam0:%r};\n" % (N, C, RHO0, round(s, 4), round(tx, 3), round(ty, 3), LAM0) +
          "// [x, y] in map pixels for a latitude and longitude, on the same projection as the outlines.\n"
          "function geoProject(lat,lon){var r=Math.PI/180,P=GEO_P,rho=Math.sqrt(P.c-2*P.n*Math.sin(lat*r))/P.n,th=P.n*(lon-P.lam0)*r;\n"
          "  return[P.s*rho*Math.sin(th)+P.tx,P.ty-P.s*(P.rho0-rho*Math.cos(th))]}\n")
    open(a.out, "w").write(js)
    print("wrote", a.out, len(js), "bytes,", len(out), "states")

if __name__ == "__main__": main()
